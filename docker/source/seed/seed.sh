  echo "FORCE_RESEED=true, dropping old source tables..."
  mysql_exec <<'SQL'
DROP TABLE IF EXISTS cif_mapping;
DROP TABLE IF EXISTS perkara;
DROP TABLE IF EXISTS identitas;
SQL
