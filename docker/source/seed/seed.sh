    1 + MOD(seq.n - 1, 120) AS id_upt_num,
    1 + MOD(FLOOR((seq.n - 1) / 120), 9999) AS seq_num,
    2010 + MOD(FLOOR((seq.n - 1) / (120 * 9999)), 15) AS year_num,
    1 + MOD(FLOOR((seq.n - 1) / (120 * 9999 * 15)), 12) AS month_num,
    1 + MOD(FLOOR((seq.n - 1) / (120 * 9999 * 15 * 12)), 28) AS day_num
  FROM (
    SELECT
      a.n
      + b.n * 10
      + c.n * 100
      + d.n * 1000
      + e.n * 10000
      + f.n * 100000
      + 1 AS n
    FROM (SELECT 0 AS n UNION ALL SELECT 1 UNION ALL SELECT 2 UNION ALL SELECT 3 UNION ALL SELECT 4 UNION ALL SELECT 5 UNION ALL SELECT 6 UNION ALL SELECT 7 UNION ALL SELECT 8 UNION ALL SELECT 9) a
    CROSS JOIN (SELECT 0 AS n UNION ALL SELECT 1 UNION ALL SELECT 2 UNION ALL SELECT 3 UNION ALL SELECT 4 UNION ALL SELECT 5 UNION ALL SELECT 6 UNION ALL SELECT 7 UNION ALL SELECT 8 UNION ALL SELECT 9) b
    CROSS JOIN (SELECT 0 AS n UNION ALL SELECT 1 UNION ALL SELECT 2 UNION ALL SELECT 3 UNION ALL SELECT 4 UNION ALL SELECT 5 UNION ALL SELECT 6 UNION ALL SELECT 7 UNION ALL SELECT 8 UNION ALL SELECT 9) c
    CROSS JOIN (SELECT 0 AS n UNION ALL SELECT 1 UNION ALL SELECT 2 UNION ALL SELECT 3 UNION ALL SELECT 4 UNION ALL SELECT 5 UNION ALL SELECT 6 UNION ALL SELECT 7 UNION ALL SELECT 8 UNION ALL SELECT 9) d
    CROSS JOIN (SELECT 0 AS n UNION ALL SELECT 1 UNION ALL SELECT 2 UNION ALL SELECT 3 UNION ALL SELECT 4 UNION ALL SELECT 5 UNION ALL SELECT 6 UNION ALL SELECT 7 UNION ALL SELECT 8 UNION ALL SELECT 9) e
    CROSS JOIN (SELECT 0 AS n UNION ALL SELECT 1 UNION ALL SELECT 2 UNION ALL SELECT 3 UNION ALL SELECT 4 UNION ALL SELECT 5 UNION ALL SELECT 6 UNION ALL SELECT 7 UNION ALL SELECT 8 UNION ALL SELECT 9) f
  ) seq
  WHERE seq.n <= @seed_rows
) src;

INSERT INTO perkara (
  NOMOR_INDUK,
  ID_UPT,
  STATUS_PERKARA,
  UPDATED_AT
)
SELECT
  it.NOMOR_INDUK,
  SUBSTRING(it.NOMOR_INDUK, 1, 3) AS ID_UPT,
  ELT(1 + MOD(CAST(RIGHT(it.NOMOR_INDUK, 4) AS UNSIGNED), 3), 'aktif', 'banding', 'inkracht') AS STATUS_PERKARA,
  it.UPDATED_AT
FROM identitas it
WHERE MOD(CAST(RIGHT(it.NOMOR_INDUK, 4) AS UNSIGNED), 10) <> 0;

INSERT INTO cif_mapping (
  NOMOR_INDUK,
  CIF_NUMBER,
  CREATED_AT
)
SELECT
  it.NOMOR_INDUK,
  CONCAT('CIF', it.NOMOR_INDUK) AS CIF_NUMBER,
  COALESCE(it.CREATED, CURRENT_TIMESTAMP) AS CREATED_AT
FROM identitas it
WHERE MOD(CAST(RIGHT(it.NOMOR_INDUK, 4) AS UNSIGNED), 13) = 0;
