#!/bin/sh
set -eu

MYSQL_HOST="${MYSQL_HOST:-source-db}"
MYSQL_PORT="${MYSQL_PORT:-3306}"
MYSQL_DATABASE="${MYSQL_DATABASE:-sdp_pusat}"
MYSQL_USER="${MYSQL_USER:-root}"
MYSQL_PASSWORD="${MYSQL_PASSWORD:-rootpass}"
SEED_ROWS="${SEED_ROWS:-10000}"
FORCE_RESEED="${FORCE_RESEED:-false}"

echo "Waiting for MariaDB at ${MYSQL_HOST}:${MYSQL_PORT}..."
until mariadb-admin --protocol=tcp -h "${MYSQL_HOST}" -P "${MYSQL_PORT}" \
  -u"${MYSQL_USER}" -p"${MYSQL_PASSWORD}" ping --silent >/dev/null 2>&1
do
  sleep 2
done

mysql_exec() {
  mariadb --protocol=tcp \
    -h "${MYSQL_HOST}" -P "${MYSQL_PORT}" \
    -u"${MYSQL_USER}" -p"${MYSQL_PASSWORD}" \
    "${MYSQL_DATABASE}" "$@"
}

mysql_exec_server() {
  mariadb --protocol=tcp \
    -h "${MYSQL_HOST}" -P "${MYSQL_PORT}" \
    -u"${MYSQL_USER}" -p"${MYSQL_PASSWORD}" "$@"
}

echo "Ensuring database ${MYSQL_DATABASE} and readonly grants..."
mysql_exec_server <<SQL
CREATE DATABASE IF NOT EXISTS \`${MYSQL_DATABASE}\`;
CREATE USER IF NOT EXISTS 'readonly_source_user'@'%' IDENTIFIED BY 'source_pass';
GRANT SELECT ON \`${MYSQL_DATABASE}\`.* TO 'readonly_source_user'@'%';
FLUSH PRIVILEGES;
SQL

